"""
evaluate_escalation.py
-----------------------
Evaluates the escalation engine against ground-truth labels in the golden set.

Metrics:
  - Precision, Recall, F1 for ESCALATE class
  - Accuracy
  - Confusion matrix

The golden set's 'expected_action' column serves as ground truth.
Predictions are generated by running the escalation engine on each example.
"""

from __future__ import annotations

import logging
import sys
from pathlib import Path

import pandas as pd
import numpy as np

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from src.config import (
    GOLDEN_EVAL_PATH,
    RESULTS_DIR,
    RANDOM_SEED,
    EMBEDDING_CLASSIFIER_PATH,
    FAISS_INDEX_PATH,
    FAISS_METADATA_PATH,
)
from src.intent_classifier import EmbeddingClassifier
from src.escalation import decide_escalation
from src.preprocessing import clean_text
from src.utils import setup_logging, save_json, ensure_dir

logger = logging.getLogger(__name__)


def _load_or_train_classifier(df: pd.DataFrame) -> EmbeddingClassifier:
    """Load saved classifier or train a fresh one if not found."""
    if EMBEDDING_CLASSIFIER_PATH.exists():
        logger.info("Loading saved EmbeddingClassifier…")
        return EmbeddingClassifier.load()

    from sklearn.model_selection import train_test_split
    train_df, _ = train_test_split(df, train_size=0.8, stratify=df["intent"], random_state=RANDOM_SEED)
    clf = EmbeddingClassifier()
    clf.fit(train_df["message"].tolist(), train_df["intent"].tolist())
    clf.save()
    return clf


def run_escalation_evaluation() -> dict:
    """Evaluate escalation engine and return metrics."""
    from sklearn.metrics import (
        accuracy_score, precision_score, recall_score, f1_score, confusion_matrix
    )

    if not GOLDEN_EVAL_PATH.exists():
        raise FileNotFoundError(
            f"Golden set not found at {GOLDEN_EVAL_PATH}.\n"
            "Run: python evaluation/create_golden_set.py"
        )

    df = pd.read_csv(GOLDEN_EVAL_PATH)
    df = df.dropna(subset=["message", "intent", "expected_action"]).copy()
    df["message"] = df["message"].fillna("").astype(str)

    logger.info("Evaluating escalation on %d examples…", len(df))

    # Load or train classifier for confidence scores
    clf = _load_or_train_classifier(df)

    predictions = []
    prediction_reasons = []
    for _, row in df.iterrows():
        text = clean_text(str(row["message"]))
        intent = str(row["intent"])

        # Get confidence from classifier
        try:
            pred = clf.predict_single(text)
            confidence = pred["confidence"]
        except Exception:
            confidence = 0.0

        # No retrieval examples available for golden set (no index for test set)
        # Use empty list as conservative case → will apply low retrieval quality rule
        esc_result = decide_escalation(
            text=text,
            intent=intent,
            confidence=confidence,
            historical_examples=[],   # conservative: test set has no retrieval index
        )
        predictions.append(esc_result["decision"])
        prediction_reasons.append(esc_result["reason"])

    y_true = df["expected_action"].tolist()
    y_pred = predictions
    labels = ["AUTO-HANDLE", "ESCALATE"]

    accuracy = accuracy_score(y_true, y_pred)
    precision = precision_score(y_true, y_pred, pos_label="ESCALATE", average="binary", zero_division=0)
    recall = recall_score(y_true, y_pred, pos_label="ESCALATE", average="binary", zero_division=0)
    f1 = f1_score(y_true, y_pred, pos_label="ESCALATE", average="binary", zero_division=0)
    cm = confusion_matrix(y_true, y_pred, labels=labels).tolist()

    metrics = {
        "accuracy": round(accuracy, 4),
        "escalation_precision": round(precision, 4),
        "escalation_recall": round(recall, 4),
        "escalation_f1": round(f1, 4),
        "confusion_matrix": cm,
        "confusion_matrix_labels": labels,
        "n_examples": len(df),
        "n_escalated_true": int(sum(1 for y in y_true if y == "ESCALATE")),
        "n_escalated_pred": int(sum(1 for y in y_pred if y == "ESCALATE")),
    }

    ensure_dir(RESULTS_DIR)
    save_json(metrics, RESULTS_DIR / "escalation_metrics.json")

    # Save predictions for failure analysis
    result_df = df.copy()
    result_df["predicted_action"] = y_pred
    result_df["escalation_reason"] = prediction_reasons
    result_df["correct"] = result_df["expected_action"] == result_df["predicted_action"]
    result_df.to_csv(RESULTS_DIR / "escalation_predictions.csv", index=False)

    print("\n=== ESCALATION EVALUATION RESULTS ===")
    print(f"Accuracy          : {metrics['accuracy']:.4f}")
    print(f"ESCALATE Precision : {metrics['escalation_precision']:.4f}")
    print(f"ESCALATE Recall    : {metrics['escalation_recall']:.4f}")
    print(f"ESCALATE F1        : {metrics['escalation_f1']:.4f}")
    print(f"Confusion Matrix   :")
    print(f"  Labels: {labels}")
    for i, row_cm in enumerate(cm):
        print(f"  {labels[i]:12s}: {row_cm}")

    return metrics


if __name__ == "__main__":
    setup_logging()
    run_escalation_evaluation()
